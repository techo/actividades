        <h1 class="doc-title">Declaración de Responsabilidad y Normas del Voluntariado</h1>
        <p class="doc-subtitle">Bienvenida persona voluntaria</p>

        <p>
        Es un honor para TECHO darte la bienvenida. Tu participación, compromiso y energía son esenciales para construir, junto a las familias de asentamientos populares, una sociedad más justa y sin pobreza. Creemos en el poder del encuentro y estamos convencidos que el trabajo en equipo entre el voluntariado y comunidades genera cambios reales y transforma realidades.
        </p>

        <p>
        A continuación, encontrarás detalladamente, todos los compromisos que asumís como persona voluntaria y las condiciones de participación en todas las actividades de TECHO.
        </p>
        <p>
        El presente acuerdo tiene carácter voluntario y no genera relación laboral, contractual, ni de subordinación entre la persona voluntaria y TECHO. La participación en las actividades es de libre voluntad, sin retribución económica ni beneficio financiero.
        </p>

        <h2>Compromisos de la Persona Voluntaria</h2>
        <p class="doc-note">Al firmar esta carta, te comprometés a:</p>

        <ul>
            <li>Respetar las reglas de cada actividad y los valores institucionales de TECHO: convicción, excelencia, optimismo, diversidad y solidaridad.</li>
            <li>Actuar en conformidad con la misión y el propósito de TECHO.</li>
            <li>Participar con responsabilidad y compromiso, procurando realizar un trabajo de calidad.</li>
            <li>Mantener un trato respetuoso con voluntarios/as, familias y demás personas involucradas.</li>
            <li>Estar dispuesto/a a reflexionar críticamente sobre la problemática de la pobreza y las experiencias vividas.</li>
            <li>Mantener la debida confidencialidad sobre información recibida en el curso de las actividades, cuando su difusión pueda afectar derechos personales.</li>
            <li>No realizar proselitismo político-partidario ni religioso en representación de TECHO.</li>
            <li>Impulsar y promover el trabajo en equipo.</li>
            <li>Cumplir con las normas de seguridad establecidas, evitando situaciones de riesgo para sí mismo/a y para los demás.</li>
            <li>No consumir drogas ilícitas ni alcohol durante las actividades.</li>
            <li>No realizar actos de violencia, sexuales ni de acoso hacia ninguna persona en el marco de las actividades.</li>
            <li>Respetar y proteger los derechos de niños, niñas y adolescentes en todas las actividades de TECHO, actuando con responsabilidad y evitando cualquier conducta que pueda poner en riesgo su integridad física, emocional o psicológica. Ante cualquier situación sospechosa, el/la voluntario/a deberá reportarla inmediatamente al equipo coordinador.</li>
            <li>Escuchar y seguir todas las orientaciones de las personas que serán identificadas como sus líderes en la actividad. Cualquier incidente que resulte de la no observancia de las orientaciones será de entera responsabilidad de la persona voluntaria.</li>
            <li>Liberar expresamente a TECHO de toda responsabilidad por cualquier daño personal, material, lesión o fallecimiento que pudiera ocurrir durante su participación como persona voluntaria, ya sea dentro o fuera de las actividades organizadas por la institución. Esta exoneración de responsabilidad se extiende a cualquier circunstancia derivada directa o indirectamente de su labor voluntaria.</li>
            <li>Ceder a TECHO de manera gratuita, irrevocable e indefinidamente el derecho a usar mi nombre e imagen en cualquier material de TECHO, incluidos sitios web de Internet y redes sociales, cualquier tipo de publicidad o material gráfico; cualquier fotografía, video, película, dibujo o representación. Asimismo, renuncio a todo tipo de compensación monetaria por concepto de uso de nombre e imagen antes mencionado.</li>
            <li>Autorizar a TECHO al tratamiento de los datos personales de la persona voluntaria, conforme a la política de tratamiento de datos que se encuentra publicada en el sitio web <a href="http://www.techo.org/">www.techo.org</a>, que la persona voluntaria declara conocer y aceptar.</li>
            <li>Utilizar adecuadamente los distintivos y la acreditación de la organización de voluntariado en forma responsable y en cumplimiento de las reglas establecidas.</li>
        </ul>

        <p class="doc-note">
            El incumplimiento de cualquiera de estos compromisos podrá implicar la expulsión inmediata de la persona voluntaria de la actividad o de la institución.
        </p>

        <h2>Inscripción y registro</h2>
        <ul>
            <li>
                <b>Registro obligatorio:</b> Para participar en las actividades de TECHO, se requiere una inscripción previa y haber aceptado el presente acuerdo. Si no estás debidamente inscripto/a, TECHO no asumirá ningún compromiso para con la persona.
            </li>
            <li>
                <b>Firma única para todas las actividades:</b> Una vez firmada esta carta, tendrá validez para todas las actividades de TECHO.
            </li>
        </ul>

        <h2>Uso de herramientas eléctricas y seguridad</h2>
        <ul>
            <li>
                <b>Prohibición del uso de herramientas eléctricas:</b> No se permite el uso de sierras circulares, amoladoras, taladros eléctricos u otras herramientas eléctricas.
            </li>
            <li>
                <b>Responsabilidad individual:</b> En caso de incumplimiento, TECHO no se hará responsable de accidentes derivados de su uso.
            </li>
        </ul>

        <h2>Exención de responsabilidad</h2>
        <p>
            La persona voluntaria reconoce y acepta que participa en las actividades de TECHO bajo su propia responsabilidad y que TECHO no será responsable por daños personales, materiales, lesiones o fallecimiento que resulten durante su estancia como persona voluntaria.
        </p>

        <h2>Compromisos de TECHO</h2>
        <p class="doc-note">TECHO se compromete a:</p>
        <ul>
            <li>Garantizar la infraestructura necesaria para la actividad.</li>
            <li>Proveer implementos necesarios, salvo aquellos que se soliciten específicamente a cada voluntario/a.</li>
            <li>Brindar capacitaciones técnicas mínimas para el buen desempeño del voluntariado.</li>
            <li>Facilitar espacios de evaluación para compartir experiencias.</li>
            <li>Promover condiciones de seguridad, prevención de riesgos y salubridad.</li>
            <li>Reembolsar gastos previamente aprobados.</li>
            <li>Resguardar la confidencialidad de los datos personales según normativa vigente.</li>
        </ul>

        <h2>Antecedentes de la persona voluntaria</h2>
        <p>
            La persona voluntaria declara bajo su exclusiva responsabilidad que no cuenta con antecedentes penales ni procesos judiciales pendientes por delitos relacionados con violencia, abuso, acoso, delitos sexuales, trata de personas, explotación infantil u otros delitos que puedan poner en riesgo la integridad de las personas con quienes interactúa en el marco de las actividades de TECHO.
        </p>
        <p>
            Asimismo, se compromete a informar a TECHO en caso de que su situación judicial se modifique durante su participación en las actividades. TECHO se reserva el derecho de solicitar documentación respaldatoria en caso de ser necesario.
        </p>
        <p>
            TECHO podrá solicitar, en cualquier momento, la presentación de un certificado de antecedentes penales expedido por la autoridad competente.
        </p>
        <p>
            El falseamiento de esta declaración o la omisión de información relevante podrá derivar en la exclusión inmediata del voluntariado y, en caso de corresponder, en la notificación a las autoridades competentes.
        </p>

        <h2>Modificación del acuerdo</h2>
        <p>
            TECHO se reserva el derecho de modificar, actualizar o complementar el presente acuerdo cuando lo considere necesario, notificando dichos cambios a los voluntarios a través de los medios oficiales de comunicación. La continuidad en la participación en actividades de TECHO implicará la aceptación de dichas modificaciones.
        </p>

        <h2>Vigencia del acuerdo</h2>
        <p>
            <b>Firma única para todas las actividades en territorio: </b>Una vez que firmes esta carta, será válida para todas las actividades en las que participes.
        </p>
        <p>
            La firma del presente documento implica que la persona voluntaria declara haber leído, comprendido y aceptado las normas aquí establecidas, comprometiéndose a cumplirlas con responsabilidad y buena fe en todas las actividades de TECHO.
        </p>
